@app.get("/api/received")
async def received(limit: int = 200):
    if not LOG.exists():
        return {"items": []}
    lines = LOG.read_text().splitlines()[-limit:]
    return {"items": [json.loads(x) for x in lines][::-1]}


@app.post("/api/reset")
async def reset():
    LOG.write_text("")
    return {"ok": True}


